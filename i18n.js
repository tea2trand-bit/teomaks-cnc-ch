const LANG_KEY = "teomaksLang";
const DEFAULT_LANG = "de";

function currentLang() {
  return window.__lang === "en" ? "en" : "de";
}

const ATTR_MAP = {
  "data-i18n-aria-label": "aria-label",
  "data-i18n-placeholder": "placeholder",
  "data-i18n-title": "title",
  "data-i18n-alt": "alt"
};

function applyLang(lang) {
  if (lang !== "en" && lang !== "de") lang = DEFAULT_LANG;
  const dict = I18N[lang];
  window.__lang = lang;
  document.documentElement.setAttribute("lang", lang);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] != null) el.textContent = dict[key];
  });

  Object.keys(ATTR_MAP).forEach((dataAttr) => {
    document.querySelectorAll("[" + dataAttr + "]").forEach((el) => {
      const key = el.getAttribute(dataAttr);
      if (dict[key] != null) el.setAttribute(ATTR_MAP[dataAttr], dict[key]);
    });
  });

  if (dict["meta.title"]) document.title = dict["meta.title"];
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && dict["meta.description"]) metaDesc.setAttribute("content", dict["meta.description"]);

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const active = btn.getAttribute("data-lang") === lang;
    btn.classList.toggle("active", active);
    btn.setAttribute("aria-pressed", active ? "true" : "false");
  });

  try { localStorage.setItem(LANG_KEY, lang); } catch (e) {}

  // Re-render the calendar so the month title follows the active language.
  if (typeof window.renderCalendar === "function") window.renderCalendar();
  if (typeof window.updateProjectUiLanguage === "function") window.updateProjectUiLanguage();
}

(function initI18n() {
  let saved = DEFAULT_LANG;
  try { saved = localStorage.getItem(LANG_KEY) || DEFAULT_LANG; } catch (e) {}

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => applyLang(btn.getAttribute("data-lang")));
  });

  applyLang(saved);

  // Contact form: translated inline success / error messages via the official
  // Netlify AJAX submission. The form markup (name, data-netlify, honeypot,
  // hidden form-name) is unchanged, so Netlify still detects and stores it.
  const form = document.querySelector('form[name="contact"]');
  const success = document.getElementById("formSuccess");
  const error = document.getElementById("formError");
  if (form) {
    form.addEventListener("submit", async (e) => {
      e.preventDefault();
      const dict = I18N[currentLang()];
      const btn = form.querySelector('button[type="submit"]');
      const btnLabel = btn ? btn.textContent : "";
      if (success) success.hidden = true;
      if (error) error.hidden = true;
      if (btn) { btn.disabled = true; btn.textContent = dict["contact.sending"]; }
      try {
        const res = await fetch("/", {
          method: "POST",
          headers: { "Content-Type": "application/x-www-form-urlencoded" },
          body: new URLSearchParams(new FormData(form)).toString()
        });
        if (!res.ok) throw new Error("Bad response");
        form.reset();
        if (success) success.hidden = false;
      } catch (err) {
        if (error) error.hidden = false;
      } finally {
        if (btn) { btn.disabled = false; btn.textContent = btnLabel; }
      }
    });
  }
})();
